#ifndef	__MTWN_MT7610_DESC_H__
#define	__MTWN_MT7610_DESC_H__

/* fields for the rxd_rxinfo entry */
#define	MT7610_RXDESC_RXINFO_BA				(1 << 0)
#define	MT7610_RXDESC_RXINFO_DATA			(1 << 1)
#define	MT7610_RXDESC_RXINFO_NULL			(1 << 2)
#define	MT7610_RXDESC_RXINFO_FRAG			(1 << 3)
#define	MT7610_RXDESC_RXINFO_UNICAST			(1 << 4)
#define	MT7610_RXDESC_RXINFO_MULTICAST			(1 << 5)
#define	MT7610_RXDESC_RXINFO_BROADCAST			(1 << 6)
#define	MT7610_RXDESC_RXINFO_MYBSS			(1 << 7)
#define	MT7610_RXDESC_RXINFO_CRCERR			(1 << 8)
#define	MT7610_RXDESC_RXINFO_ICVERR			(1 << 9)
#define	MT7610_RXDESC_RXINFO_MICERR			(1 << 10)
#define	MT7610_RXDESC_RXINFO_AMSDU			(1 << 11)
#define	MT7610_RXDESC_RXINFO_HTC			(1 << 12)
#define	MT7610_RXDESC_RXINFO_RSSI			(1 << 13)
#define	MT7610_RXDESC_RXINFO_L2PAD			(1 << 14)
#define	MT7610_RXDESC_RXINFO_AMPDU			(1 << 15)
#define	MT7610_RXDESC_RXINFO_DECRYPT			(1 << 16)
#define	MT7610_RXDESC_RXINFO_BSSIDX3			(1 << 17)
#define	MT7610_RXDESC_RXINFO_WAPI_KEY			(1 << 18)
#define	MT7610_RXDESC_RXINFO_PN_LEN			0x00380000
#define	MT7610_RXDESC_RXINFO_PN_LEN_S			19
#define	MT7610_RXDESC_RXINFO_SW_FTYPE0			(1 << 22)
#define	MT7610_RXDESC_RXINFO_SW_FTYPE1			(1 << 23)
#define	MT7610_RXDESC_RXINFO_PROBE_RESP			(1 << 24)
#define	MT7610_RXDESC_RXINFO_BEACON			(1 << 25)
#define	MT7610_RXDESC_RXINFO_DISASSOC			(1 << 26)
#define	MT7610_RXDESC_RXINFO_DEAUTH			(1 << 27)
#define	MT7610_RXDESC_RXINFO_ACTION			(1 << 28)
#define	MT7610_RXDESC_RXINFO_TCP_SUM_ERR		(1 << 30)
#define	MT7610_RXDESC_RXINFO_IP_SUM_ERR			(1 << 31)

#define	MT7610_RXDESC_RXWI_CTL_WCID			0x000000ff
#define	MT7610_RXDESC_RXWI_CTL_WCID_S			0

#define	MT7610_RXDESC_RXWI_CTL_KEY_IDX			0x00000300
#define	MT7610_RXDESC_RXWI_CTL_KEY_IDX_S		8
#define	MT7610_RXDESC_RXWI_CTL_BSS_IDX			0x00001c00
#define	MT7610_RXDESC_RXWI_CTL_BSS_IDX_S		10
#define	MT7610_RXDESC_RXWI_CTL_UDF			0x0000e000
#define	MT7610_RXDESC_RXWI_CTL_UDF_S			13
#define	MT7610_RXDESC_RXWI_CTL_MPDU_LEN			0x3fff0000
#define	MT7610_RXDESC_RXWI_CTL_MPDU_LEN_S		16
#define	MT7610_RXDESC_RXWI_CTL_EOF			(1 << 31)

#define	MT7610_RXDESC_RXWI_TID				0x000f
#define	MT7610_RXDESC_RXWI_TID_S			0
#define	MT7610_RXDESC_RXWI_SN				0xfff0
#define	MT7610_RXDESC_RXWI_SN_S				4

#define	MT7610_RXDESC_RXWI_RATE_INDEX			0x003f
#define	MT7610_RXDESC_RXWI_RATE_INDEX_S			0
#define	MT7610_RXDESC_RXWI_RATE_LDPC			(1 << 6)
#define	MT7610_RXDESC_RXWI_RATE_BW			0x0180
#define	MT7610_RXDESC_RXWI_RATE_BW_S			7
#define	MT7610_RXDESC_RXWI_RATE_SGI			(1 << 9)
#define	MT7610_RXDESC_RXWI_RATE_STBC			(1 << 10)
#define	MT7610_RXDESC_RXWI_RATE_LDPC_EXSYM		(1 << 11)
#define	MT7610_RXDESC_RXWI_RATE_PHY			0xe000
#define	MT7610_RXDESC_RXWI_RATE_PHY_S			13

#define	MT7610_RXDESC_RATE_INDEX_VHT_IDX		0x0000000f
#define	MT7610_RXDESC_RATE_INDEX_VHT_IDX_S		0
#define	MT7610_RXDESC_RATE_INDEX_VHT_NSS		0x00000030
#define	MT7610_RXDESC_RATE_INDEX_VHT_NSS_S		4

/**
 * @brief RX descriptor layout.
 *
 * The fields here are all little endian.
 */
struct mtwn_mt7610_rx_desc {
	uint32_t	rxd_rxinfo;
	uint32_t	rxd_ctl;
	uint16_t	rxd_tid_sn;
	uint16_t	rxd_rate;
	uint8_t		rxd_rssi[4];
	uint32_t	rxd_bbp_rxinfo[4];
} __packed;

#endif	/* __MTWN_MT7610_DESC_H__ */
